@router.get("/list", response_model=List[ChatResponse])
async def get_chats(
    skip: int = 0,
    limit: int = 100,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Список чатов пользователя"""
    from app.models.chat import ChatSession
    
    result = await db.execute(
        select(ChatSession)
        .where(ChatSession.user_id == current_user.id)
        .order_by(ChatSession.created_at.desc(),ChatSession.id.desc())
        .offset(skip)
        .limit(limit)
    )
    chats = result.scalars().all()
    from app.services.chat_titles import generic_title, update_automatic_title, suggest_chat_title
    generic=[chat for chat in chats if generic_title(chat.title)]
    if generic:
        ids=[chat.id for chat in generic]
        # A list refresh can run while the interview is applying an answer.
        # Read its latest state under the same row lock before repairing a title.
        generic = (await db.execute(select(ChatSession).where(ChatSession.id.in_(ids))
                   .order_by(ChatSession.id).with_for_update().execution_options(populate_existing=True))).scalars().all()
        first_message_id = (select(Message.id).where(Message.chat_id == ChatSession.id, Message.role == 'user')
                            .order_by(Message.id).limit(1).correlate(ChatSession).scalar_subquery())
        first = dict((await db.execute(select(ChatSession.id, Message.content)
                      .join(Message, Message.id == first_message_id).where(ChatSession.id.in_(ids)))).all())
        changed=False
        for chat in generic:
            if not generic_title(chat.title):
                continue
            if chat.document_workflow:
                state=dict(chat.document_workflow)
                previous_title = chat.title
                update_automatic_title(chat,state,first.get(chat.id,''))
                if state != chat.document_workflow or chat.title != previous_title:
                    chat.document_workflow=state
                    changed=True
            elif first.get(chat.id):
                chat.title=suggest_chat_title(text=first[chat.id]);changed=True
        if changed:await db.commit()
    return [ChatResponse.model_validate(chat) for chat in chats]

@router.get("/{chat_id}/history", response_model=List[MessageSchema])
async def get_chat_history(
    chat_id: int,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """История сообщений выбранного чата пользователя."""
    chat_result = await db.execute(
        select(ChatSession).where(
            ChatSession.id == chat_id,
            ChatSession.user_id == current_user.id,
        )
    )
    chat_obj = chat_result.scalar_one_or_none()
    if not chat_obj:
        raise HTTPException(status_code=404, detail="Chat not found")

    messages_result = await db.execute(
        select(Message)
        .where(Message.chat_id == chat_id)
        .order_by(Message.created_at.asc(), Message.id.asc())
    )
    messages = messages_result.scalars().all()
    return [_message_for_history(message) for message in messages]

