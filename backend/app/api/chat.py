@router.patch("/{chat_id}/title", response_model=ChatResponse)
async def update_chat_title(
    chat_id: int,
    payload: UpdateChatTitleRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    title = (payload.title or "").strip()
    if not title:
        raise HTTPException(status_code=422, detail="Title cannot be empty")

    result = await db.execute(
        select(ChatSession).where(
            ChatSession.id == chat_id,
            ChatSession.user_id == current_user.id,
        )
    )
    chat_obj = result.scalar_one_or_none()
    if not chat_obj:
        raise HTTPException(status_code=404, detail="Chat not found")

    chat_obj.title = title[:200]
    if chat_obj.document_workflow:
        chat_obj.document_workflow={**chat_obj.document_workflow,'title_manual':True, 'automatic_title':None}
    db.add(chat_obj)
    await db.commit()
    await db.refresh(chat_obj)
    return ChatResponse.model_validate(chat_obj)

@router.post("/{chat_id}/send_stream")
async def send_message_stream(
    chat_id: int,
    message_in: SendStreamRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Стриминговый чат с ИИ-юристом (RAG + GigaChat)
    ✅ АСИНХРОННЫЙ!
    """
    from app.models.chat import ChatSession, Message
    
    async def error_stream(error_text: str):
        yield f"data: {error_text}\n\n"
        yield "data: [DONE]\n\n"

    try:
        # 1. Проверяем доступ к чату
        result = await db.execute(
            select(ChatSession).where(
                ChatSession.id == chat_id,
                ChatSession.user_id == current_user.id
            ).with_for_update().execution_options(populate_existing=True)
        )
        chat_obj = result.scalar_one_or_none()
        if not chat_obj:
            raise HTTPException(status_code=404, detail="Chat not found")

        if (chat_obj.document_workflow and chat_obj.document_workflow.get('phase') != 'cancelled'
                and requests_new_case(message_in.content)):
            # Do not save another case's facts as answers in the current intake.
            # They would otherwise be picked up by history recovery next turn.
            message = ('Документ по прежнему делу сохранён. Для нового дела укажите, какой документ подготовить, '
                       'например «Составь иск по другому делу».') if chat_obj.document_workflow.get('phase') == 'ready' else (
                       'В этой переписке уже идёт подготовка документа. Завершите или отмените её перед новым делом.')
            raise HTTPException(409, detail={'code': 'document_interview_active', 'message': message})

        # 2. Сохраняем сообщение пользователя
        user_message = Message(
            chat_id=chat_id,
            content=message_in.content,
            role="user"
        )
        db.add(user_message)
        await db.flush()
        # The retry path needs the pair even if the transport closes before its first event.
        assistant_message = Message(chat_id=chat_id, content="", role="assistant")
        db.add(assistant_message)
        await db.commit()
        await db.refresh(user_message)
        await db.refresh(assistant_message)

        # Авто-тайтл: если чат ещё не назван, берём краткий смысл из первого сообщения.
        try:
            from app.services.chat_titles import generic_title, suggest_chat_title
            if not chat_obj.document_workflow and generic_title(chat_obj.title):
                chat_obj.title = suggest_chat_title(text=message_in.content)
                db.add(chat_obj)
                await db.commit()
        except Exception as title_error:
            print(f"⚠️ Chat title update unavailable: {title_error}")

        try:
            await sync_user_interests_from_message(
                db,
                user_id=current_user.id,
                chat_id=chat_id,
                text=message_in.content,
            )
        except Exception as interest_error:
            print(f"⚠️ Interest sync unavailable: {interest_error}")

        # 4. RAG контекст + изменения законов + прикреплённые документы.
        context = {"docs": [], "rag": "", "law_db_size": 0, "attached_documents": []}
        if not chat_obj.document_workflow or chat_obj.document_workflow.get('phase') == 'cancelled':
            try:
                context["rag"], context["rag_sources"] = build_rag_bundle(message_in.content)
                relevant_laws = await get_relevant_law_changes_for_user(
                    db, user_id=current_user.id, chat_id=chat_id, limit=3)
                if not relevant_laws:
                    relevant_laws = await _law_change_crud.get_multi(db, limit=3)
                context["docs"] = [f"Изменение: {law.change_title}" for law in relevant_laws]
                context["law_db_size"] = await _law_change_crud.count(db)
            except Exception as context_error:
                print(f"⚠️ RAG context unavailable: {context_error}")

        if message_in.attachment_ids:
            try:
                context["attached_documents"] = await load_user_documents_text(
                    db,
                    user_id=current_user.id,
                    document_ids=message_in.attachment_ids,
                )
            except Exception as attachment_error:
                print(f"⚠️ Attached documents unavailable: {attachment_error}")
    except HTTPException:
        raise
    except Exception as pre_stream_error:
        traceback.print_exc()
        return StreamingResponse(
            error_stream(f"Ошибка до стриминга: {pre_stream_error}"),
            media_type="text/event-stream",
            headers={"Cache-Control": "no-cache", "Connection": "keep-alive"}
        )
    
    # 5. Реальный ответ от GigaChat + SSE стриминг
    assistant_id = assistant_message.id
    async def generate_stream():
        answer_saved = False

        async def persist_interrupted_reply():
            """Leave a resumable turn instead of an empty assistant bubble."""
            try:
                await db.rollback()
                await db.execute(
                    update(Message)
                    .where(Message.id == assistant_id, Message.chat_id == chat_id, Message.content == '')
                    .values(content=_INTERRUPTED_STREAM_REPLY)
                )
                await db.commit()
            except Exception:
                await db.rollback()

        try:
            yield f"data: {json.dumps({'message_id': assistant_message.id}, ensure_ascii=False)}\n\n"

            # История диалога нужна модели, чтобы НЕ повторять вопросы и использовать уже данные факты.
            # Берём последние сообщения (включая только что сохранённое сообщение пользователя).
            history_limit = 20
            history_result = await db.execute(
                select(Message)
                .where(Message.chat_id == chat_id)
                .order_by(Message.created_at.desc(), Message.id.desc())
                .limit(history_limit)
            )
            history_messages = list(reversed(history_result.scalars().all()))
            chat_history = "\n".join(
                f"{m.role}: {m.content}".strip()
                for m in history_messages
                if (m.content or "").strip()
            )

            # Lock the interview row while applying a turn. Persistent JSON, rather
            # than the truncated history, is the source of previously supplied facts.
            locked = (await db.execute(select(ChatSession).where(
                ChatSession.id == chat_id, ChatSession.user_id == current_user.id,
            ).with_for_update().execution_options(populate_existing=True))).scalar_one()
            workflow = locked.document_workflow
            workflow_boundary = max(int((workflow or {}).get('context_start_message_id') or 0),
                                    int((workflow or {}).get('workflow_start_message_id') or 0))
            if workflow and (user_message.id < workflow_boundary
                             or user_message.id <= (workflow.get('last_applied_message_id') or 0)):
                # Another tab can start an interview after this message was
                # committed but before its streaming callback acquires the lock.
                # Keep the old message; never apply it to the newer workflow.
                nlp_result = NLPGenerateResult(
                    text='Это сообщение сохранено в истории. Подготовка документа уже продолжилась. '
                         'Ориентируйтесь на последний ответ в чате.',
                    cached=False, usage=TokenUsage(0, 0, 0, False))
            elif workflow and workflow.get("phase") != "cancelled":
                from app.services.document_workflow import file_request_kind, facts_digest_for_interview
                from app.services.document_conversation import conversational_interview_turn
                # Resolve relative dates against the user's message timestamp,
                # not a stale saved workflow or the server's UTC calendar day.
                workflow = dict(locked.document_workflow)
                factual_message = user_message
                retry = message_in.content.strip(' .!').casefold() in _DOCUMENT_RETRY_WORDS
                if retry and not workflow.get('pending_answer'):
                    interrupted = _interrupted_document_answer(history_messages, workflow, workflow_boundary, user_message.id)
                    if interrupted is not None:
                        factual_message = interrupted
                turn_timestamp = factual_message.created_at or datetime.now(timezone.utc)
                if turn_timestamp.tzinfo is None:
                    turn_timestamp = turn_timestamp.replace(tzinfo=timezone.utc)
                workflow['turn_date'] = turn_timestamp.astimezone(
                    timezone(timedelta(hours=5))
                ).date().isoformat()
                prior_turns = (await db.execute(select(Message.content).where(
                    Message.chat_id == chat_id, Message.role == "user",
                    Message.id >= max(int(workflow.get('context_start_message_id') or 0),
                                      int(workflow.get('workflow_start_message_id') or 0)),
                    Message.id <= factual_message.id,
                ).order_by(Message.created_at.asc(), Message.id.asc()))).scalars().all()
                previous_ready = locked.document_workflow.get("phase") == "ready"
                previous_facts = facts_digest_for_interview(workflow)
                workflow, text, usage = await conversational_interview_turn(
                    workflow, factual_message.content, prior_user_turns=list(prior_turns))
                workflow['last_applied_message_id'] = user_message.id
                from app.services.chat_titles import update_automatic_title
                update_automatic_title(locked,workflow,message_in.content)
                from app.api.documents import interview_file_reply
                locked.document_workflow = workflow
                if (not previous_ready or retry or file_request_kind(message_in.content)
                        or facts_digest_for_interview(workflow) != previous_facts):
                    text = await interview_file_reply(locked, current_user.id, db, text)
                await db.execute(update(ChatSession).where(ChatSession.id == chat_id).values(document_workflow=locked.document_workflow,title=locked.title))
                nlp_result = NLPGenerateResult(text=text, cached=False, usage=usage)
            else:
                nlp_result = await _nlp_service.generate_response(
                    user_query=message_in.content,
                    context=context,
                    chat_history=chat_history,
                )
            full_response = nlp_result.text
            await record_llm_usage(
                db,
                user_id=current_user.id,
                chat_id=chat_id,
                message_id=assistant_message.id,
                model=settings.llm_model,
                cached=nlp_result.cached,
                usage=nlp_result.usage,
                commit=False,
            )

            # Persist the answer and its cited references before signalling completion.
            # Streaming may start after dependency cleanup detached this ORM object.
            # An explicit UPDATE persists the reply regardless of the identity map.
            await db.execute(
                update(Message).where(Message.id == assistant_id, Message.chat_id == chat_id)
                .values(content=full_response)
            )
            await save_chat_law_references(
                db, user_id=current_user.id, chat_id=chat_id, user_message_id=user_message.id,
                assistant_message_id=assistant_message.id,
                references=getattr(nlp_result, "references", ()),
            )
            await db.commit()

            answer_saved = True

            # Стриминг по символам-блокам с сохранением пробелов и переносов
            chunk_size = 24
            for i in range(0, len(full_response), chunk_size):
                part = full_response[i:i + chunk_size]
                chunk = f"data: {json.dumps({'content': part}, ensure_ascii=False)}\n\n"
                yield chunk
                await asyncio.sleep(0.05)

            yield "data: [DONE]\n\n"

        except asyncio.CancelledError:
            if not answer_saved:
                await asyncio.shield(persist_interrupted_reply())
            raise
        except Exception as e:
            await db.rollback()
            error_text = f"Ошибка GigaChat: {str(e)}"
            if not answer_saved:
                await db.execute(
                    update(Message)
                    .where(Message.id == assistant_id)
                    .values(content=error_text)
                )
                await db.commit()
            yield f"data: {json.dumps({'content': error_text}, ensure_ascii=False)}\n\n"
            yield "data: [DONE]\n\n"
    
    stream = generate_stream()
    if chat_obj.document_workflow and chat_obj.document_workflow.get('phase') != 'cancelled':
        stream = _document_stream_with_keepalive(stream)
    return StreamingResponse(
        stream,
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "Connection": "keep-alive"}
    )

@router.post("/feedback")
async def submit_feedback(
    payload: FeedbackCreate,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Оценка ответа ИИ (JSON: message_id, rating)."""
    result = await db.execute(
        select(Message)
        .join(ChatSession, Message.chat_id == ChatSession.id)
        .where(
            Message.id == payload.message_id,
            ChatSession.user_id == current_user.id,
        )
    )
    message = result.scalar_one_or_none()

    if not message:
        raise HTTPException(status_code=404, detail="Message not found")

    message.rating = payload.rating
    db.add(message)
    await db.commit()

    return {"message": f"Feedback '{payload.rating}' submitted successfully"}

