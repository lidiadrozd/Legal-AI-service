_INTERRUPTED_STREAM_REPLY = (
    'Ответ пользователя сохранён, но соединение оборвалось до завершения ответа. '
    'Если следующего вопроса нет, напишите «повтори» — повторно вводить сведения не нужно.'
)
_DOCUMENT_RETRY_WORDS = {'повтори', 'повторить', 'попробуй ещё раз', 'попробуй еще раз'}


async def _document_stream_with_keepalive(stream, interval=15):
    """Send SSE comments while extraction or Word generation is still running."""
    pending = asyncio.create_task(anext(stream))
    try:
        while True:
            done, _ = await asyncio.wait((pending,), timeout=interval)
            if not done:
                yield ': keep-alive\n\n'
                continue
            try:
                event = pending.result()
            except StopAsyncIteration:
                return
            yield event
            pending = asyncio.create_task(anext(stream))
    finally:
        pending.cancel()
        await asyncio.gather(pending, return_exceptions=True)
        await stream.aclose()


def _interrupted_document_answer(history, workflow, boundary, retry_id):
    """Find the interrupted factual turn immediately preceding a retry."""
    previous = [row for row in history if boundary <= row.id < retry_id]
    while len(previous) >= 2:
        user, answer = previous[-2:]
        if (user.role != 'user' or answer.role != 'assistant'
                or (answer.content or '').strip() not in {'', _INTERRUPTED_STREAM_REPLY}):
            break
        if (user.content or '').strip(' .!').casefold() not in _DOCUMENT_RETRY_WORDS:
            if user.id > (workflow.get('last_applied_message_id') or 0):
                return user
            break
        del previous[-2:]
    return None


def _message_for_history(message: Message) -> MessageSchema:
    result = MessageSchema.model_validate(message)
    if message.role != 'assistant' or (message.content or '').strip():
        return result
    created_at = message.created_at
    if created_at is None:
        return result
    if created_at.tzinfo is None:
        created_at = created_at.replace(tzinfo=timezone.utc)
    if datetime.now(timezone.utc) - created_at < timedelta(minutes=1):
        return result
    # Old versions could leave an empty assistant row after an SSE disconnect.
    # Expose a resumable instruction without mutating an answer that may still
    # be generated by another active request.
    return result.model_copy(update={'content': _INTERRUPTED_STREAM_REPLY})


